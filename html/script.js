// Audio setup
const audioAssets = {
    click: new Audio('assets/click.mp3'),
    join: new Audio('assets/join.mp3'),
    start: new Audio('assets/start.mp3'),
    kill: new Audio('assets/kill.mp3'),
    win: new Audio('assets/win.mp3')
};

function playSound(name) {
    if (audioAssets[name]) {
        audioAssets[name].currentTime = 0;
        audioAssets[name].play().catch(() => {});
    }
}

// Localization Helper
function applyLocalization(locales) {
    document.querySelectorAll('[data-locale]').forEach(el => {
        const key = el.getAttribute('data-locale');
        if (locales[key]) {
            if (el.tagName === 'INPUT' && el.type === 'text') {
                el.placeholder = locales[key];
            } else {
                el.innerText = locales[key];
            }
        }
    });
}

// Tab Switching
document.querySelectorAll('.tab-btn').forEach(btn => {
    btn.addEventListener('click', () => {
        if (btn.dataset.tab === currentTab) return;
        playSound('click');
        document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');

        currentTab = btn.dataset.tab;

        // Show/Hide Tab Contents
        if (currentTab === 'create') {
            document.getElementById('tab-browser').classList.remove('active');
            document.getElementById('tab-create').classList.add('active');
        } else {
            document.getElementById('tab-browser').classList.add('active');
            document.getElementById('tab-create').classList.remove('active');

            // Show/Hide Filters
            document.getElementById('free-slots-filter').style.display = (currentTab === 'list') ? 'flex' : 'none';

            fetchLobbies();
        }
    });
});

