function showLobbyArea(lobby, asHost) {
    currentLobby = lobby;
    isHost = asHost;
    playSound('join');

    document.getElementById('lobby-title').innerText = lobby.name.toUpperCase();
    document.getElementById('lobby-waiting-area').style.display = 'flex';
    document.getElementById('btn-start-game').style.display = asHost ? 'block' : 'none';
    document.getElementById('btn-close-lobby').style.display = asHost ? 'block' : 'none';

    document.getElementById('lobby-info-summary').innerHTML = `
        <p>MAP: ${lobby.mapLabel}</p>
        <p>MODE: ${lobby.mode.toUpperCase()}</p>
        <p>TIME: ${lobby.roundTime} MIN</p>
        <p>KILL LIMIT: ${lobby.killLimit}</p>
    `;

    // Show settings editor for host in custom lobbies
    const editor = document.getElementById('lobby-settings-editor');
    if (asHost && !lobby.isPersistent) {
        editor.style.display = 'block';
        document.getElementById('edit-kill-limit').value = lobby.killLimit;
        document.getElementById('edit-respawn-time').value = lobby.respawnTime;
        document.getElementById('edit-friendly-fire').checked = lobby.friendlyFire;
        document.getElementById('edit-vehicles-allowed').checked = lobby.vehiclesAllowed;
    } else {
        editor.style.display = 'none';
    }
}

